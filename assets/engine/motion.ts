/* ── вычисление кривой ────────────────────────────────────────────────────
 * Курсор ведётся по времени из JS (часы сцены ставятся на паузу, когда
 * вкладка скрыта, — CSS-переход так не умеет). Поэтому кривая считается
 * здесь, тем же cubic-bezier, что и в CSS.
 */
export function ease(name: EaseName, t: number) {
  const [x1, y1, x2, y2] = EASE[name]
  if (t <= 0) return 0
  if (t >= 1) return 1
  const bez = (a: number, b: number, s: number) =>
    3 * a * s * (1 - s) ** 2 + 3 * b * s ** 2 * (1 - s) + s ** 3
  // x(s) монотонна на [0, 1] — бинарный поиск надёжнее Ньютона на крутых кривых.
  let lo = 0
  let hi = 1
  let s = t
  for (let i = 0; i < 24; i++) {
    s = (lo + hi) / 2
    if (bez(x1, x2, s) < t) lo = s
    else hi = s
  }
  return bez(y1, y2, s)
}
