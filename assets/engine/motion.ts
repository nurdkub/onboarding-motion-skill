/**
 * Пружина как CSS `linear()`: затухающее колебание, разложенное по точкам.
 * `response` — период колебания, с; `damping` — доля критического затухания
 * (1 — без перелёта, меньше — с перелётом). Те же два числа, какими задаёт
 * пружину Apple (SwiftUI `.spring(response:dampingFraction:)`), поэтому
 * анимацию можно сверять с их платформой один в один.
 */
export function springEase(response: number, damping: number, duration: number, points = 40) {
  const at = springAt(response, damping)
  const values = Array.from({ length: points + 1 }, (_, i) =>
    i === points ? 1 : Number(at((i / points) * (duration / 1000)).toFixed(4)),
  )
  return `linear(${values.join(', ')})`
}

/**
 * Положение пружины во времени `t`, с: 0 → 1, с перелётом при `damping` < 1.
 * `damping` = 1 — критическое затухание (Apple `.smooth`): без перелёта.
 */
export function springAt(response: number, damping: number) {
  const w = (2 * Math.PI) / response
  if (damping >= 1) return (t: number) => 1 - Math.exp(-w * t) * (1 + w * t)
  const wd = w * Math.sqrt(1 - damping ** 2)
  return (t: number) =>
    1 - Math.exp(-damping * w * t) * (Math.cos(wd * t) + ((damping * w) / wd) * Math.sin(wd * t))
}

