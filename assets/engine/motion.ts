/**
 * Движение — одна пружина Apple `.smooth` на всё (решение 07.10.2026: выбрана
 * на странице сравнения «Онбординг: варианты анимации» из семи систем —
 * Apple Smooth / Snappy / Bouncy, Material 3, IBM Carbon, Fluent 2 и прежней
 * нашей). Пружина без отскока: всё мягко доезжает до места, ничего не
 * перелетает. Так устроены системы Apple: одно семейство движения, а роли
 * отличаются длительностью, не формой.
 *
 * Роли остаются по имени — `enter` (появление), `exit` (уход), `move` (путь
 * курсора, перемещение на экране), — но форма у них одна. Форма пружины не
 * зависит от длительности: она растянута так, что за отведённое время
 * успевает сесть (99 % пути), поэтому одна запись `linear()` годится для
 * любой длительности.
 */
export const SPRING = {
  /** Период пружины, с — как `response` у SwiftUI `.smooth` (0,5 с). */
  response: 0.5,
  /** Затухание: 1 — критическое, без отскока (`.smooth`). */
  damping: 1,
  /** Длительность, под которую задан период: `duration/slow`. */
  settle: 500,
} as const

export type EaseName = 'enter' | 'exit' | 'move'

/** Доля пути по доле времени для пружины `SPRING` — для того, что движок ведёт из JS (курсор, круг нажатия). */
export function smoothAt(p: number) {
  if (p <= 0) return 0
  if (p >= 1) return 1
  return springAt(SPRING.response, SPRING.damping)((p * SPRING.settle) / 1000)
}

/** Та же пружина для CSS — `linear()` по 40 точкам. */
export const SMOOTH = `linear(${Array.from({ length: 41 }, (_, i) =>
  i === 40 ? 1 : Number(smoothAt(i / 40).toFixed(4)),
).join(', ')})`

/** Кривая роли для CSS. Роли разные, форма одна — пружина `SPRING`. */
export function cssEase(_name: EaseName) {
  return SMOOTH
}

