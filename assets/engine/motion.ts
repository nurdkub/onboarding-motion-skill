/* ── вычисление кривой ────────────────────────────────────────────────────
 * Курсор ведётся по времени из JS (часы сцены ставятся на паузу, когда
 * вкладка скрыта, — CSS-переход так не умеет). Поэтому кривая считается
 * здесь, тем же cubic-bezier, что и в CSS.
 */
export function ease(_name: EaseName, t: number) {
  return smoothAt(t)
}
