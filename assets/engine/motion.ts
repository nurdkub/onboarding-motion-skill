/**
 * Кривые. Всего три, и по роли, а не по вкусу:
 *
 * - `enter` — появление. Резкий старт, долгое торможение: та же кривая, что
 *   у накладок ДС (`src/styles/motion.css`), чтобы окно в сцене появлялось
 *   так же, как настоящее;
 * - `exit` — уход. Мягкий старт, разгон: уходящее не должно задерживать глаз;
 * - `move` — перемещение внутри экрана (курсор). Симметричная ease-in-out:
 *   объект, который видно и в начале, и в конце пути, разгоняется и тормозит.
 */
export const EASE = {
  enter: [0.16, 1, 0.3, 1],
  exit: [0.7, 0, 0.84, 0],
  move: [0.65, 0, 0.35, 1],
} as const satisfies Record<string, readonly [number, number, number, number]>

export type EaseName = keyof typeof EASE

export function cssEase(name: EaseName) {
  return `cubic-bezier(${EASE[name].join(', ')})`
}

